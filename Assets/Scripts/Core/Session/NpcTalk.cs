        /// <summary>闲聊台词；dayKey 决定今天说哪一句。</summary>
        public static string SmallTalkLine(string npcId, int dayKey)
        {
            if (!Small.TryGetValue(npcId, out string[] lines) || lines.Length == 0) return "对方笑着点点头，和你聊了几句。";
            return lines[((dayKey % lines.Length) + lines.Length) % lines.Length];
        }

        public static int LifeChapterTotal => LifeUnlock.Length;

        /// <summary>第 chapter 段（0 起）人生故事；没有则 null。</summary>
        public static string LifeStory(string npcId, int chapter)
        {
            if (!Life.TryGetValue(npcId, out string[] lines) || chapter < 0 || chapter >= lines.Length) return null;
            return lines[chapter];
        }
