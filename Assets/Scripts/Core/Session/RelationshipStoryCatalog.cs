        internal RelationshipStory(string personId, int district, string title, string activityId,
            string intro, string invitation, string duringOuting, string afterOuting, string partnerReply, string friendReply,
            string partnerFollowUp, string friendFollowUp)
        {
            PersonId = personId;
            District = district;
            Title = title;
            ActivityId = activityId;
            Intro = intro;
            Invitation = invitation;
            DuringOuting = duringOuting;
            AfterOuting = afterOuting;
            PartnerReply = partnerReply;
            FriendReply = friendReply;
            PartnerFollowUp = partnerFollowUp;
            FriendFollowUp = friendFollowUp;
        }
    }

